export const emojis: Emoji[] = Object.entries(groups).flatMap(
  ([category, values]) =>
    values.map(([value, name]) => ({ value, name, category })),
);

export const emojiName = (value: string): string =>
  emojis.find((emoji) => emoji.value === value)?.name ?? value;

export const filterEmoji = (
  category: string,
  query: string,
  recent: string[],
): Emoji[] => {
  const normalized = query.toLocaleLowerCase("ru").replaceAll("ё", "е").trim();

  if (normalized) {
    return emojis.filter(
      (emoji) =>
        emoji.name.replaceAll("ё", "е").includes(normalized) ||
        emoji.value === normalized,
    );
  }

  if (category === "recent") {
    return recent
      .map((value) => emojis.find((emoji) => emoji.value === value))
      .filter((emoji): emoji is Emoji => Boolean(emoji));
  }

  return emojis.filter((emoji) => emoji.category === category);
};
