import Foundation

// onboarding-r4 composition and approved onboarding-r5 copy, 04.11.2026.
enum OnboardingSlide: Int, CaseIterable, Identifiable {
    case invitation, meetings, conversation, date, poll, task, album, plans
    var id: Int { rawValue }
    var title: String {
        switch self {
        case .invitation: "Позовите друзей\nна встречу."
        case .meetings: "Ваши встречи\nв списке и календаре."
        case .conversation: "Обсуждайте детали\nв чате встречи."
        case .date: "Предложите\nдругую дату."
        case .poll: "Договоритесь,\nгде встретиться."
        case .task: "Договоритесь,\nкто что подготовит."
        case .album: "Соберите фотографии\nвстречи."
        case .plans: "Откройте\nсвои встречи."
        }
    }
    var text: String {
        switch self {
        case .invitation:
            "Назначьте дату и отправьте ссылку.\nПо ответам друзей будет понятно, кого ждать."
        case .meetings:
            "Откройте весь список или выберите день,\nчтобы посмотреть запланированные встречи."
        case .conversation:
            "Переписка, фото и файлы остаются внутри\nвстречи. Можно поставить реакцию\nили посмотреть, кто прочитал сообщение."
        case .date:
            "Участники проголосуют за подходящий день.\nЕсли один вариант наберёт большинство,\nдата встречи изменится автоматически."
        case .poll:
            "Предложите новое место. Если после опроса\nбольшинство проголосовавших будет за,\nоно станет местом встречи."
        case .task:
            "Друг станет ответственным, когда примет\nпредложенную задачу. Когда всё будет готово,\nон сможет отметить её выполненной."
        case .album:
            "Участники могут добавить свои снимки.\nСмотрите их в общем альбоме\nили скачайте все фотографии сразу."
        case .plans: "Отдельная регистрация не нужна."
        }
    }
    var exampleLabel: String {
        switch self {
        case .invitation: "Настоящая карточка встречи и варианты ответа Приду, Возможно и Не смогу."
        case .meetings: "Реальные карточки встреч и календарь с датами встреч."
        case .conversation: "Настоящие фото и файл в чате, реакция и отметка Прочитали 4."
        case .date: "Реальный опрос о дате с вариантами 7 и 8 ноября."
        case .poll: "Реальная карточка голосования о смене места: у Саши дома."
        case .task: "Настоящая задача Заказать пиццу до и после принятия Мишей."
        case .album:
            "Фотографии друзей за настолками и ужином в общем альбоме встречи. Можно скачать все фото."
        case .plans: "Настоящая карточка будущей личной встречи."
        }
    }
}
